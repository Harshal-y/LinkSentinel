@app.before_request
def security_checks():
    if request.method == 'POST':
        supplied = request.form.get('_csrf', '')
        expected = session.get('_csrf', '')
        if not supplied or not expected or not secrets.compare_digest(supplied, expected):
            abort(400, 'Invalid or missing security token. Refresh the page and try again.')

@app.after_request
def security_headers(response):
    response.headers.setdefault('X-Content-Type-Options', 'nosniff')
    response.headers.setdefault('X-Frame-Options', 'DENY')
    response.headers.setdefault('Referrer-Policy', 'strict-origin-when-cross-origin')
    response.headers.setdefault('Content-Security-Policy', "default-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; form-action 'self'; frame-ancestors 'none'")
    return response


