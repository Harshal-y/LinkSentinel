-- LinkSentinel Supabase PostgreSQL schema
-- The Flask application creates these tables automatically on startup.
-- Run manually only if you prefer creating the schema in Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    scanned_at TEXT NOT NULL,
    url TEXT NOT NULL,
    risk_score INTEGER NOT NULL,
    verdict TEXT NOT NULL,
    findings TEXT NOT NULL,
    report_json TEXT
);

CREATE INDEX IF NOT EXISTS idx_scans_user_date
    ON public.scans(user_id, id DESC);
