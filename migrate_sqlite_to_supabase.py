"""One-time copy of LinkSentinel SQLite users/scans into Supabase PostgreSQL.
Run from the project root with DATABASE_URL set in .env.
"""
import os
import sqlite3
from dotenv import load_dotenv
import psycopg

load_dotenv()
url = os.environ.get('DATABASE_URL', '').strip()
sqlite_path = os.environ.get('DATABASE_PATH', 'linksentinel.db')
if not url:
    raise SystemExit('DATABASE_URL is missing. Set it in .env first.')
if not os.path.exists(sqlite_path):
    raise SystemExit(f'SQLite database not found: {sqlite_path}')

if 'sslmode=' not in url:
    url += ('&' if '?' in url else '?') + 'sslmode=require'

src = sqlite3.connect(sqlite_path)
src.row_factory = sqlite3.Row
with psycopg.connect(url) as dst:
    with dst.cursor() as cur:
        cur.execute('''CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL, email TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL, created_at TEXT NOT NULL)''')
        cur.execute('''CREATE TABLE IF NOT EXISTS scans (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
            scanned_at TEXT NOT NULL, url TEXT NOT NULL, risk_score INTEGER NOT NULL,
            verdict TEXT NOT NULL, findings TEXT NOT NULL, report_json TEXT)''')
        cur.execute('CREATE INDEX IF NOT EXISTS idx_scans_user_date ON scans(user_id, id DESC)')
        users = src.execute('SELECT id,username,email,password_hash,created_at FROM users').fetchall()
        for row in users:
            cur.execute('''INSERT INTO users(id,username,email,password_hash,created_at)
                VALUES(%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING''',
                tuple(row))
        scans = src.execute('''SELECT id,user_id,scanned_at,url,risk_score,verdict,findings,report_json
                               FROM scans''').fetchall()
        for row in scans:
            cur.execute('''INSERT INTO scans(id,user_id,scanned_at,url,risk_score,verdict,findings,report_json)
                VALUES(%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING''',
                tuple(row))
        for table in ('users', 'scans'):
            cur.execute(f"SELECT setval(pg_get_serial_sequence('{table}','id'), COALESCE((SELECT MAX(id) FROM {table}), 1), EXISTS(SELECT 1 FROM {table}))")
    dst.commit()
src.close()
print(f'Migration complete: copied {len(users)} users and {len(scans)} scans (existing IDs were left unchanged).')
