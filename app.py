def rate_limit(key, limit=12, seconds=60):
    now = time.time(); q = REQUEST_BUCKETS[key]
    while q and now - q[0] > seconds: q.popleft()
    if len(q) >= limit: return False
    q.append(now); return True


def public_ip(ip_text):
    ip = ipaddress.ip_address(ip_text.split('%')[0])
    return ip.is_global and not (ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved or ip.is_multicast)


def resolve_host(host):
    try:
        infos = socket.getaddrinfo(host, None, type=socket.SOCK_STREAM)
        ips = sorted({item[4][0] for item in infos})
        if not ips: return [], 'The hostname did not resolve to an IP address.'
        # Fail closed if ANY DNS answer is non-public, mitigating mixed-answer SSRF and rebinding.
        blocked = [x for x in ips if not public_ip(x)]
        if blocked: return ips, 'The hostname resolves to a private, local, or non-public address. Network inspection was stopped.'
        return ips, None
    except Exception as exc:
        return [], f'DNS resolution failed: {type(exc).__name__}'


def normalize_url(raw):
    raw = (raw or '').strip()
    if not raw: raise ValueError('Enter a URL to scan.')
    if len(raw) > MAX_URL_LENGTH: raise ValueError('The URL is too long. Maximum length is 2,048 characters.')
    if re.match(r'^[a-zA-Z][a-zA-Z0-9+.-]*:', raw) and '://' not in raw:
        raise ValueError('Unsupported URL scheme. Only HTTP and HTTPS URLs are accepted.')
    if '://' not in raw: raw = 'https://' + raw
    parts = urlsplit(raw); scheme = parts.scheme.lower()
    if scheme not in ('http', 'https'): raise ValueError('Only HTTP and HTTPS URLs are supported.')
    if not parts.hostname: raise ValueError('The URL does not contain a valid hostname.')
    if parts.username or parts.password: raise ValueError('URLs containing embedded usernames or passwords are not accepted.')
    try: port = parts.port
    except ValueError: raise ValueError('The URL contains an invalid port.')
    if port not in (None, 80, 443): raise ValueError('For safety, only standard HTTP (80) and HTTPS (443) ports are scanned.')
    host = parts.hostname.encode('idna').decode('ascii').lower().rstrip('.')
    if not host or len(host) > 253: raise ValueError('Invalid hostname length.')
    if ':' not in host:
        if not re.fullmatch(r'[a-z0-9.-]+', host): raise ValueError('The hostname contains unsupported characters.')
        if any(not label or len(label) > 63 or label.startswith('-') or label.endswith('-') for label in host.split('.')): raise ValueError('The hostname format is invalid.')
    netloc = f'[{host}]' if ':' in host else host
    if port: netloc += f':{port}'
    return urlunsplit((scheme, netloc, parts.path or '/', parts.query, '')), scheme, host, port or (443 if scheme == 'https' else 80)


def add_finding(findings, level, title, detail, points=0):
    findings.append({'level': level, 'title': title, 'detail': detail, 'points': points})


def url_heuristics(url, host):
    findings, score = [], 0; parts = urlsplit(url); low = url.lower()
    def flag(level, title, detail, points):
        nonlocal score
        score += points; add_finding(findings, level, title, detail, points)
    if len(url) > 100: flag('warning', 'Unusually long URL', 'Long URLs can be used to hide the actual destination.', 10)
    if len(url) > 180: flag('danger', 'Very long URL', 'The URL is considerably longer than typical website links.', 10)
    if '@' in parts.netloc: flag('danger', 'At-sign in URL authority', 'This can make a misleading URL appear to belong to another host.', 25)
    try: ipaddress.ip_address(host); flag('warning', 'IP address used as hostname', 'The link points directly to an IP address instead of a domain name.', 15)
    except ValueError: pass
    if 'xn--' in host: flag('warning', 'Punycode hostname', 'Internationalized domain encoding can be legitimate, but may disguise look-alike characters.', 15)
    if len(host.split('.')) >= 5: flag('warning', 'Many subdomains', 'The hostname contains several subdomain levels.', 8)
    matched = [w for w in ('login','verify','account','secure','update','password','wallet','banking','gift','free') if w in low]
    if matched: flag('warning', 'Potentially sensitive URL wording', 'Contains: ' + ', '.join(matched), min(15, len(matched)*5))
    if parts.scheme == 'http': flag('warning', 'Unencrypted HTTP', 'The connection does not use HTTPS transport encryption.', 20)
    if host.count('-') >= 3: flag('warning', 'Several hyphens in hostname', 'This pattern can occur in deceptive or disposable domains.', 8)
    if re.search(r'%[0-9a-fA-F]{2}', url): flag('warning', 'Percent-encoded characters', 'Encoded URL characters can obscure the visible destination.', 5)
    if '%25' in low: flag('warning', 'Possible double URL encoding', 'Double-encoded characters can make a destination harder to interpret.', 5)
    if parts.path.lower().endswith(('.exe','.scr','.bat','.cmd','.msi','.apk','.iso','.js')): flag('danger', 'Potentially risky download extension', 'The URL path ends with an executable or script-related file extension.', 15)
    if not findings: add_finding(findings, 'good', 'No basic URL red flags found', 'The URL passed the initial structural checks. This is not proof that it is safe.', 0)
    return score, findings


def inspect_endpoint(host, ip, port, use_tls, request_target):
    result = {'status':None,'headers':{},'cert':None,'error':None,'redirect':None,'tls_error_code':None,'tls_error_message':None}
    raw_sock = None
    try:
        raw_sock = socket.create_connection((ip, port), timeout=TIMEOUT); conn = raw_sock
        if use_tls:
            context = ssl.create_default_context()
            try: conn = context.wrap_socket(raw_sock, server_hostname=host)
            except ssl.SSLCertVerificationError as exc:
                result['error'] = 'TLS certificate validation failed.'
                result['tls_error_code'] = getattr(exc, 'verify_code', None)
                result['tls_error_message'] = getattr(exc, 'verify_message', str(exc))[:240]
                return result
            cert_bin = conn.getpeercert(binary_form=True); cert = conn.getpeercert()
            xcert = x509.load_der_x509_certificate(cert_bin); pub = xcert.public_key()
            expiry = cert.get('notAfter')
            expiry_dt = datetime.strptime(expiry, '%b %d %H:%M:%S %Y %Z').replace(tzinfo=timezone.utc) if expiry else None
            result['cert'] = {'issuer':', '.join('='.join(x) for group in cert.get('issuer',[]) for x in group),
                'subject':', '.join('='.join(x) for group in cert.get('subject',[]) for x in group),
                'expires':expiry_dt.strftime('%Y-%m-%d %H:%M UTC') if expiry_dt else 'Unknown',
                'expired':bool(expiry_dt and expiry_dt < datetime.now(timezone.utc)),
                'sha256':hashlib.sha256(cert_bin).hexdigest().upper(),
                'signature_hash':getattr(xcert.signature_hash_algorithm,'name','Unknown'),
                'public_key_type':type(pub).__name__.replace('PublicKey',''), 'public_key_bits':getattr(pub,'key_size',None)}
        target = request_target.encode('ascii','ignore')
        host_header = (f'[{host}]' if ':' in host else host).encode('ascii')
        conn.sendall(b'HEAD ' + target + b' HTTP/1.1\r\nHost: ' + host_header + b'\r\nUser-Agent: LinkSentinel/2.2\r\nConnection: close\r\n\r\n')
        stream = conn.makefile('rb'); result['status'] = stream.readline(4096).decode('latin-1','replace').strip()
        for _ in range(80):
            line = stream.readline(8192)
            if not line or line in (b'\r\n',b'\n'): break
            decoded = line.decode('latin-1','replace')
            if ':' in decoded:
                k,v = decoded.split(':',1); result['headers'][k.strip().lower()] = v.strip()
        if 'location' in result['headers']:
            dest_url = urljoin(('https://' if use_tls else 'http://') + host + '/', result['headers']['location'])
            dest = urlsplit(dest_url)
            result['redirect'] = {'url':dest_url,'host_changed':bool(dest.hostname and dest.hostname.lower()!=host.lower()),'https_downgrade':use_tls and dest.scheme.lower()=='http'}
    except (ssl.SSLError, socket.timeout, OSError, ValueError) as exc:
        result['error'] = f'Connection check unavailable: {type(exc).__name__}: {str(exc)[:160]}'
    finally:
        try:
            if raw_sock: raw_sock.close()
        except Exception: pass
    return result


def urlhaus_lookup(url):
    key = os.environ.get('URLHAUS_AUTH_KEY','').strip()
    if not key: return {'status':'not_configured','message':'URLhaus lookup is optional and is not configured. Add URLHAUS_AUTH_KEY to enable it.'}
    try:
        r = requests.post('https://urlhaus-api.abuse.ch/v1/url/', data={'url':url}, headers={'Auth-Key':key}, timeout=5)
        data = r.json(); status = data.get('query_status','unknown')
        if status == 'ok': return {'status':'listed','message':'This exact URL is listed in URLhaus threat-intelligence data. Treat it as a strong warning.','threat':data.get('threat','unknown'),'date_added':data.get('date_added'),'url_status':data.get('url_status')}
        if status == 'no_results': return {'status':'not_listed','message':'No exact URL match was returned by URLhaus. This does not prove the URL is safe.'}
        return {'status':'unavailable','message':f'URLhaus returned status: {status}.'}
    except Exception as exc:
        return {'status':'unavailable','message':f'URLhaus lookup unavailable ({type(exc).__name__}).'}


def scan_url(raw):
    url, scheme, host, port = normalize_url(raw); score, findings = url_heuristics(url,host)
    parts = urlsplit(url); target = parts.path or '/'
    if parts.query: target += '?' + parts.query
    ips, dns_error = resolve_host(host); dns = {'addresses':ips,'error':dns_error}
    endpoint = {'status':None,'headers':{},'cert':None,'error':None,'redirect':None,'tls_error_code':None,'tls_error_message':None}
    if dns_error:
        score += 20; add_finding(findings,'warning','DNS / network check blocked',dns_error,20)
    elif ips:
        attempts = [inspect_endpoint(host,ip,port,scheme=='https',target) for ip in ips]
        endpoint = next((a for a in attempts if a['status'] or a['cert']), next((a for a in attempts if a.get('tls_error_code') is not None or (a.get('error') and 'TLS certificate validation failed' in a['error'])), attempts[0]))
        if endpoint['error']:
            if 'TLS certificate validation failed' in endpoint['error']:
                msg = endpoint.get('tls_error_message') or 'The TLS verifier rejected the certificate.'
                code = endpoint.get('tls_error_code')
                category = 'Certificate validation failed'
                lowmsg = msg.lower()
                if 'expired' in lowmsg: category = 'Certificate appears expired'
                elif 'hostname' in lowmsg or 'not valid for' in lowmsg: category = 'Certificate hostname mismatch'
                elif 'self-signed' in lowmsg: category = 'Self-signed certificate'
                elif 'issuer' in lowmsg or 'local issuer' in lowmsg: category = 'Untrusted certificate issuer'
                score += 25
                add_finding(findings,'danger','TLS: '+category, f'{msg} (verification code: {code if code is not None else "unavailable"}). This can be a site certificate issue or a network inspection intermediary; verify from another network.',25)
            else: add_finding(findings,'info','Connection inspection unavailable',endpoint['error']+' No risk points were added because the scanner could not establish whether the endpoint is misconfigured.',0)
        if scheme=='https' and endpoint['cert']:
            if endpoint['cert']['expired']:
                score += 30; add_finding(findings,'danger','TLS certificate expired','The server presented an expired certificate.',30)
            else: add_finding(findings,'good','TLS certificate validated','The certificate chain and hostname passed the local TLS verifier.',0)
        if endpoint['status']:
            headers = endpoint['headers']
            for h,(title,detail,points) in SECURITY_HEADERS.items():
                if h not in headers and (h!='strict-transport-security' or scheme=='https'):
                    score += points; add_finding(findings,'info',title,detail,points)
            if 'server' in headers: add_finding(findings,'info','Web server banner disclosed','The response identifies the server as: '+headers['server'][:120],0)
            if 'x-powered-by' in headers: add_finding(findings,'info','Technology banner disclosed','The response includes an X-Powered-By header.',0)
        else: add_finding(findings,'info','HTTP security headers not assessed','No readable HTTP response was received, so missing-header checks were skipped.',0)
        if endpoint['redirect']:
            red = endpoint['redirect']; add_finding(findings,'info','Redirect response detected','The server returned a redirect destination. SecureDNS reports it but does not follow it.',0)
            if red['host_changed']:
                score += 8; add_finding(findings,'warning','Redirect changes hostname','The redirect points to a different hostname: '+(urlsplit(red['url']).hostname or 'unknown'),8)
            if red['https_downgrade']:
                score += 15; add_finding(findings,'danger','HTTPS-to-HTTP downgrade redirect','The redirect destination uses unencrypted HTTP.',15)
    intel = urlhaus_lookup(url)
    if intel['status']=='listed':
        score += 50; add_finding(findings,'danger','URLhaus threat-intelligence match',intel['message'],50)
    elif intel['status']=='not_listed': add_finding(findings,'info','URLhaus lookup: no exact match',intel['message'],0)
    elif intel['status']=='unavailable': add_finding(findings,'info','URLhaus lookup unavailable',intel['message'],0)
    score = min(100,score); verdict = 'LOW RISK' if score<25 else ('SUSPICIOUS' if score<55 else 'HIGH RISK')
    return {'url':url,'host':host,'score':score,'verdict':verdict,'findings':findings,'dns':dns,'endpoint':endpoint,
            'urlhaus':intel,'scanned_at':datetime.now(timezone.utc).isoformat(),'display_time':datetime.now().astimezone().strftime('%d %b %Y, %I:%M:%S %p %Z')}


def save_scan(user_id, report):
    with connect_db() as con:
        query = 'INSERT INTO scans(user_id,scanned_at,url,risk_score,verdict,findings,report_json) VALUES(?,?,?,?,?,?,?)'
        params = (user_id,report['scanned_at'],report['url'],report['score'],report['verdict'],json.dumps(report['findings']),json.dumps(report))
        if USE_POSTGRES:
            return con.execute(query + ' RETURNING id', params).fetchone()['id']
        cur = con.execute(query, params)
        return cur.lastrowid

