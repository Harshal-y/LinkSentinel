@app.route('/login',methods=['GET','POST'])
def login():
    if request.method=='POST':
        identity=request.form.get('identity','').strip().lower(); password=request.form.get('password','')
        if not rate_limit('login:'+request.remote_addr,10,300): flash('Too many login attempts. Wait five minutes.','error')
        else:
            with connect_db() as con: user=con.execute('SELECT * FROM users WHERE lower(username)=? OR email=?',(identity,identity)).fetchone()
            if user and check_password_hash(user['password_hash'],password):
                session.clear(); session['user_id']=user['id']; session['username']=user['username']; csrf_token(); return redirect(url_for('home'))
            flash('Invalid username/email or password.','error')
    return render_template('auth.html',mode='login')

